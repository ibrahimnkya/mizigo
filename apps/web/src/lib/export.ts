import * as XLSX from "xlsx";

export interface ExportColumn {
  header: string;
  key: string;
  width?: number;
}

interface ExportOptions {
  title: string;
  subtitle?: string;
  dateRange?: string;
  generatedBy?: string;
  columns: ExportColumn[];
  data: Record<string, any>[];
  filename?: string;
}

function buildWorksheet(opts: ExportOptions): XLSX.WorkSheet {
  const { title, subtitle, dateRange, generatedBy, columns, data } = opts;

  const rows: any[][] = [];

  // ── Header block ────────────────────────────────────────────
  rows.push([title]);
  if (subtitle) rows.push([subtitle]);
  if (dateRange) rows.push([`Period: ${dateRange}`]);
  if (generatedBy) rows.push([`Generated by: ${generatedBy}`]);
  rows.push([`Generated on: ${new Date().toLocaleString()}`]);
  rows.push([]); // blank row

  // ── Summary ──────────────────────────────────────────────────
  rows.push([`Total Records: ${data.length}`]);
  rows.push([]); // blank row

  // ── Column headers ───────────────────────────────────────────
  rows.push(columns.map((c) => c.header));

  // ── Data rows ────────────────────────────────────────────────
  for (const row of data) {
    rows.push(columns.map((c) => resolveKey(row, c.key)));
  }

  // ── Footer ───────────────────────────────────────────────────
  rows.push([]); // blank row
  rows.push(["--- End of Report ---"]);

  const ws = XLSX.utils.aoa_to_sheet(rows);

  // Column widths
  ws["!cols"] = columns.map((c) => ({ wch: c.width ?? 20 }));

  // Merge title cell across columns
  if (columns.length > 1) {
    const mergeWidth = columns.length - 1;
    ws["!merges"] = [{ s: { r: 0, c: 0 }, e: { r: 0, c: mergeWidth } }];
  }

  return ws;
}

function resolveKey(obj: Record<string, any>, key: string): any {
  // Supports dot notation: "user.name"
  return key.split(".").reduce((acc, k) => acc?.[k], obj) ?? "";
}

export function downloadExcel(opts: ExportOptions): void {
  const ws = buildWorksheet(opts);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Report");
  const filename = `${opts.filename ?? opts.title.toLowerCase().replace(/\s+/g, "-")}.xlsx`;
  XLSX.writeFile(wb, filename);
}

export function downloadODS(opts: ExportOptions): void {
  const ws = buildWorksheet(opts);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Report");
  const filename = `${opts.filename ?? opts.title.toLowerCase().replace(/\s+/g, "-")}.ods`;
  XLSX.writeFile(wb, filename, { bookType: "ods" });
}
